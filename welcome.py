"""A first example using Python's print() function."""

# print() displays text and values in the console.
print("Hello, world!")

# It can also display numbers and the result of simple expressions.
print(2)
print("2 + 3")  # Quoted text is displayed as written.
print("2" + "3")  # Adding strings joins their text.
print(2 + 3)  # Adding numbers performs arithmetic.
print(2.5 + 4)
print(2 * 55)
